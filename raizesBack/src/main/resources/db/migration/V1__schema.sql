CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  perfil VARCHAR(20) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  consentimento_lgpd BOOLEAN NOT NULL DEFAULT FALSE,
  consentimento_lgpd_em TIMESTAMP WITH TIME ZONE,
  fidelidade_consentimento BOOLEAN NOT NULL DEFAULT FALSE,
  pontos_fidelidade INT NOT NULL DEFAULT 0,
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE unidades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  cidade VARCHAR(80) NOT NULL,
  ativa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  descricao VARCHAR(300),
  preco NUMERIC(12,2) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE estoques (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  quantidade INT NOT NULL CHECK (quantidade >= 0),
  CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id)
);
CREATE TABLE movimentacoes_estoque (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  tipo VARCHAR(10) NOT NULL,
  quantidade INT NOT NULL,
  motivo VARCHAR(200),
  usuario_id BIGINT,
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT REFERENCES usuarios(id),
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  canal_pedido VARCHAR(20) NOT NULL,
  status VARCHAR(30) NOT NULL,
  forma_pagamento VARCHAR(20) NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
  atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_pedidos_canal ON pedidos(canal_pedido);
CREATE INDEX idx_pedidos_status ON pedidos(status);
CREATE TABLE itens_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  quantidade INT NOT NULL CHECK (quantidade > 0),
  preco_unitario NUMERIC(12,2) NOT NULL
);
CREATE TABLE pagamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  status VARCHAR(20) NOT NULL,
  forma_pagamento VARCHAR(20) NOT NULL,
  valor NUMERIC(12,2) NOT NULL,
  transacao_id VARCHAR(60),
  mensagem VARCHAR(300),
  payload_gateway VARCHAR(2000),
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE movimentos_pontos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  pontos INT NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  descricao VARCHAR(200),
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE logs_auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT,
  acao VARCHAR(60) NOT NULL,
  entidade VARCHAR(60),
  entidade_id BIGINT,
  detalhes VARCHAR(1000),
  criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
